_SPROUT = """\
THE BOOT ON A ROPE

Nell skipped down the lane with her rope. SWISH, hop. SWISH, hop.

WHOOSH! The wind took Gran's red scarf. Up it went, and down it came, right in the middle of the biggest puddle.

"Oh dear," said Gran. "That puddle is deeper than my boots."

"I'll get it!" said Nell. She threw one end of her rope. It fell short. SPLAT! Muddy water jumped all over Gran's coat.

"Oops," said Nell.

Gran wiped her nose. "Try again, my duck."

Nell looked at her rope. It was too light to fly far. She looked at her feet. Then she grinned.

She sat down on the wall and pulled off one yellow boot. She tied the rope around it, tight, tight, tight.

"A boot?" said Gran.

"A boot," said Nell.

She swung it once. She swung it twice. Away it flew, and PLOP! It landed right on top of the scarf.

Nell pulled. The boot came sliding back, and the scarf came with it, all soggy and red.

Gran wrung it out. Nell hopped all the way home on one boot. SWISH, hop. SWISH, hop."""

_EXPLORER = """\
SEVEN CRAB ROCKS

The little yellow submarine hummed down through the green water, and Iris pressed her nose to the round window.

"One," she whispered. A rock went by with a crab sitting on top like a hat. "Two. Three."

"Are you counting again?" said Aunt Jo, who was steering.

"Crab rocks," said Iris. "Seven. Then the gap in the kelp."

Aunt Jo laughed. Iris counted everything. Stairs. Peas. The buttons in her button jar, twice a week, in case one had gone missing.

Past the kelp the sea floor opened wide, and there were the glow-fish. Hundreds of them, small as thumbs, shining blue.

Iris tapped on the glass. Tap, tap-tap. One glow-fish turned and swam right up to her finger.

"It likes that!" she said. Tap, tap-tap. Two more came.

Then the big lamp on the front of the submarine went POP.

Everything outside turned black. The glow-fish scattered like sparks.

"Ah," said Aunt Jo. Her voice had gone careful. "That's our lamp. It sits on the outside, so I can't mend it from in here. And without it I can't see the gap in the kelp."

Iris looked at the dark. Kelp was thick as a hedge and a hundred times as tall. If they steered into it, the propeller would tangle.

"There must be another light," she said, and she flipped the nearest switch.

SWISH-SWISH went the window wipers.

She flipped the next one. BLOOOORP! went the bubble horn, so loudly that Aunt Jo's cap fell off. Far away, the last few glow-fish shot behind a rock.

"Iris."

"Sorry."

Now it was darker than ever. Iris sat on her hands so they could not flip anything else. Her tummy felt tight, like a button done up wrong.

Then she thought about the one fish that had come to her finger.

She leaned to the glass. Tap, tap-tap.

Nothing.

Tap, tap-tap. Tap, tap-tap. Her finger started to ache. Aunt Jo opened her mouth, and Iris shook her head. Buttons took a long time to count, too. You just kept going.

Tap, tap-tap.

A blue dot. Then three. Then a wobbling cloud of them, crowding up to the window to see what the noise was, until the water in front of the submarine glowed like a night-light.

"Go slowly," said Iris. "They're only little."

Aunt Jo eased the submarine forward. Iris tapped with one hand and pointed with the other.

"Seven," she said, as a rock with a crab on it slid out of the dark. "No, wait. We're going backwards. That's one. I mean, it's seven on the way home."

"Which is it?"

"Left of this rock. The gap is left."

And there it was, a tall black doorway in the kelp.

Iris kept tapping the whole way through, and she counted the crab rocks home out loud, seven down to one, with the glow-fish bobbing alongside. At the sixth rock they turned back, all together, as if someone had called them for tea.

Up at the dock, Aunt Jo unscrewed the dead lamp and put it in Iris's hands. It was heavier than it looked.

"For the button jar?" she said.

Iris thought about it. "It won't fit," she said. "I'll need a bigger jar."

She tapped the side of the submarine once, to say goodnight. Tap, tap-tap. Under the dock, something small blinked blue."""

_ADVENTURER = """\
THE TOP CORNER

By Tuesday, eleven strawberries had gone from the school garden, and Dev had decided who took them.

"Callum," he said, stabbing his trowel into the soil. "He's always hanging about by the gate. And the judging is Friday, Wren. Friday! We'll have nothing to show but leaves."

Wren did not answer. She was crouched by the raised bed with her notebook, the one that was mostly birds, writing down things that did not fit.

The net over the strawberries was still pegged tight along the ground. A person would have to lift it, and nobody had. Only ripe berries were gone, and only from the back row, up against the fence. And on the wooden edge of the bed there were three small white splashes.

"It doesn't look like a person," she said.

"It looks like Callum."

At lunch Dev marched across the playground and said it to Callum's face, loudly, with half of Year Five listening. Callum went red to the ears. He said, "I never," and then he said nothing at all, and walked off.

That afternoon was Callum's turn on the watering rota. He did not come.

The hose tap needed the long key, and Mrs Abara the caretaker had already gone to her other school with it. By Wednesday morning the lettuces lay flat as wet paper and two of the bean plants had curled up brown.

Dev stared at them. "That's not my fault," he said, in the voice of someone who thought it was.

Wren went to find Mrs Abara instead of arguing. "What time do you unlock the garden gate?"

"Seven. Why?"

"Could you unlock it at half past six tomorrow? And could I sit in the shed with the door open a crack?"

Mrs Abara looked at the notebook under Wren's arm. "Bring a coat," she said.

At twenty to seven on Thursday the garden was grey and dripping and nobody was in it. Wren sat on an upturned bucket in the shed with her bike gloves on, because they were the only gloves she could find, and watched the strawberry bed.

At ten to seven a blackbird landed on the fence. He looked left, looked right, and dropped straight down behind the bed, into the top corner where the net met the fence post. The net bulged. A second later he was inside, tugging at a strawberry twice the size of his head.

Wren nearly laughed out loud. She crept close enough to see it: the plastic clip that held the net's top corner to the post had snapped, and the net sagged open there, a gap just wide enough for a determined bird. High up. Higher than the pegs. About as high as Callum could reach on tiptoe.

She found him by the bike racks before the bell.

"You were trying to fix the clip," she said.

Callum shrugged at the ground. "I couldn't reach it properly. I was going to bring a chair, but then everyone would've asked why." He kicked a pedal round. "Dev could've just asked."

"Yes," said Wren. "He could."

She told Dev all of it, and showed him the page: the time, the corner, a sketch of a blackbird with its beak full. Dev read it twice. Then he walked over to the bike racks by himself. Wren did not hear what he said. It took a while, and at one point Callum folded his arms, and at another point Dev had to look at his own shoes. But when they came back, Callum was carrying the long key.

"Got it off Mrs Abara," he said. "The beans might still come round."

The clip was the last problem. The spare ones were in a cupboard nobody could find. Wren turned her bike upside down, got out her puncture kit, and cut the old patched inner tube from her saddle bag into six fat rubber bands. Stretched round the net and the post, they held like a fist.

"Done," said Dev. "No more thief."

Wren looked up at the fence. The blackbird was back, turning his head to look at the bed with one eye and then the other.

"The front row isn't ripe till next week," she said slowly. "If we left the net off that row..."

"Wren. The judging."

"They don't judge the ones that aren't ripe."

"They judge how it looks!"

She did not push. She just wrote something in her notebook and went to help Callum with the hose.

On Friday the judge walked round with her clipboard and counted nine strawberries, a row of beans that had mostly come round, and one row of plants with the net rolled neatly back. Stuck in the soil in front of it was a lolly stick, with a label in Dev's square handwriting.

RESERVED, it said. And underneath, smaller: for the one with the orange beak."""


def build_exemplar_block(age: int) -> str:
    """Example story for ages 12 and under; empty for older readers."""
    if age <= 5:
        story, who = _SPROUT, "a 4-year-old"
    elif age <= 8:
        story, who = _EXPLORER, "a 7-year-old"
    elif age <= 12:
        story, who = _ADVENTURER, "a 10-year-old"
    else:
        return ""
    return f"""
**THE STANDARD TO MATCH** (an example written for {who}, on a different theme):
<example_story>
{story}
</example_story>
What to take from it: the hero could not be swapped for another child, because the way the problem gets solved comes out of who they are. One small moment decides everything, and the hero does it. Every limit in the story holds if you ask "why not just...?". Nobody says what was learned or explains a feeling. The last lines are a thing happening, and the story stops there.
Borrow NOTHING else: not its plot, names, objects, setting, sounds, jokes or phrases, and not its length (use the word range given below). It is shown as plain text; your answer still follows the output format in these instructions. Tell THIS reader's story, with their theme and interests.
"""
